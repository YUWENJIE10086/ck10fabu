def set_font(run,name,size,bold=None):
    run.font.name=name; run.font.size=Pt(size)
    if bold is not None: run.font.bold=bold
    rpr=run._element.get_or_add_rPr()
    rfonts=rpr.rFonts
    if rfonts is None:
        rfonts=OxmlElement("w:rFonts"); rpr.insert(0,rfonts)
    for a in ("ascii","hAnsi","eastAsia","cs"): rfonts.set(qn("w:"+a),name)

def rich(p,text):
    hits=[k for k in KEYS if k in text]
    pat="("+"|".join(map(re.escape,sorted(hits,key=len,reverse=True)))+")" if hits else None
    parts=re.split(pat,text) if pat else [text]
    for x in parts:
        if not x: continue
        r=p.add_run(x); set_font(r,BODY_FONT,16,x in KEYS)

